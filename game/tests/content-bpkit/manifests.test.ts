/** The tags a class's pseudo file states: its own CDO override line, else the nearest ancestor's (read from pseudo). */
function pseudoTags(asset: string): string[] {
  const txt = fs.readFileSync(`${PSEUDO}/${asset}.txt`, 'utf8');
  const own = /^ {4}\/\/ {3}OwnedGameplayTags = (\[.*\])$/m.exec(txt);
  if (own) return JSON.parse(own[1]) as string[];
  const parent = /^\/\/ parent chain: \/Game\/([^ .]+)/m.exec(txt);
  return parent && fs.existsSync(`${PSEUDO}/${parent[1]}.txt`) ? pseudoTags(parent[1]) : [];
}

describe('naming rule D11', () => {
  it('drops trailing and replaces inner invalid characters', () => {
    expect(mangle('疲劳了？')).toBe('疲劳了');
    expect(mangle('增加金币/收入')).toBe('增加金币_收入');
    expect(mangle('抽取特定类型卡牌到场上（碰撞）')).toBe('抽取特定类型卡牌到场上_碰撞');
    expect(mangle('科学数乘除*/')).toBe('科学数乘除');
    expect(mangle('日志//输出')).toBe('日志__输出');
  });
  it('refuses collisions', () => {
    expect(mangleAll(['唯一？', '可叠加？'], 'test')).toEqual(['唯一', '可叠加']);
    expect(() => mangleAll(['唯一？', '唯一'], 'test')).toThrow(/both mangle/);
    expect(() => mangleAll(['a/b', 'a_b'], 'test')).toThrow(/collide|both mangle/);
  });
});

