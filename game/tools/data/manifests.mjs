// Builds the blueprint-side manifests next to the tables (studio/ARCHITECTURE.md §7.1): src/content/demo/{classes,
// anims,tags,widgets,reachable}.ts and src/content/text/strings.ts. Keys of the returned map are relative to
// src/content. Deterministic: every collection is emitted in code-point order or in the dump's own order.
import fs from 'node:fs';
import path from 'node:path';
import { actorAnims, readAnims } from './anims.mjs';
import { buildClasses, createValueNormalizer, readBlueprints } from './classes.mjs';
import { computeReach } from './reach.mjs';
import { OUT_NONSKILL } from './scope.mjs';
import { readTags, redirector } from './tags.mjs';
import { buildWidgets, readWidgets } from './widgets.mjs';

const json = v => JSON.stringify(v);
const header = (source, what) =>
  `// Generated by tools/data/import-demo.mjs from ${source}. Do not edit: re-run the importer (src/content/README.md).\n// ${what}\n`;
const entries = (obj, indent = '  ') => Object.entries(obj).map(([k, v]) => `${indent}${json(k)}: ${json(v)},\n`).join('');
const list = (arr, indent = '  ') => arr.map(v => `${indent}${json(v)},\n`).join('');

export const MANIFEST_FILES = ['demo/classes.ts', 'demo/anims.ts', 'demo/tags.ts', 'demo/widgets.ts', 'demo/reachable.ts', 'text/strings.ts'];

function classesModule(classes) {
  return (
    header('dump/blueprints/CatapultHero/BP (widgets excluded)', 'The class manifest: one entry per Demo blueprint, by asset path.') +
    `import type { AssetPath, RichCurve } from './types.ts';

export type DemoClassKind = 'ability' | 'effect' | 'projectile' | 'actor' | 'card' | 'pickup' | 'decoration' | 'settlement' | 'other';

/** One Demo blueprint class. Structurally a ClassDef of src/core/sim/types.ts, plus the fields after \`reachable\`. */
export interface DemoClass {
  readonly path: AssetPath;
  readonly name: string;
  /** The parent blueprint, or null when the parent is native (see \`native\`). */
  readonly parent: AssetPath | null;
  readonly kind: DemoClassKind;
  /** CDO OwnedGameplayTags: the class's own override, else inherited from the nearest ancestor; redirects applied. */
  readonly tags: readonly string[];
  /** Variables the class declares, with their CDO defaults (mangled names, runtime-shaped values). */
  readonly vars: Readonly<Record<string, unknown>>;
  readonly timelines: Readonly<Record<string, { readonly length: number; readonly tracks: Readonly<Record<string, RichCurve>>; readonly loop: boolean; readonly autoPlay: boolean }>>;
  /** Component templates: class plus the scalar, reference and small numeric properties. */
  readonly components: Readonly<Record<string, Readonly<Record<string, unknown>>>>;
  /** Live table rows that reference the class: 'table:row'. */
  readonly rows: readonly string[];
  /** In the prototype's scope (skill classes: reachable.ts; other blueprints: not dead or out of scope). */
  readonly reachable: boolean;
  /** The native class the chain ends in, e.g. 'CatapultHero.GameplayTagActor'. */
  readonly native: string | null;
  /** CDO values of variables an ancestor blueprint declares (mangled names, runtime-shaped). */
  readonly overrides: Readonly<Record<string, unknown>>;
  /** Reachable from any live row or live blueprint (the architect's 495 for skill classes). */
  readonly live: boolean;
}

export const demoClasses: Readonly<Record<AssetPath, DemoClass>> = {
${classes.map(c => `  ${json(c.path)}: ${json(c)},\n`).join('')}};

/** The class with this asset path, or undefined. */
export function findClass(path: AssetPath): DemoClass | undefined {
  return Object.hasOwn(demoClasses, path) ? demoClasses[path] : undefined;
}

/** The ancestor chain of a class, nearest first (blueprint parents only). */
export function classAncestors(path: AssetPath): DemoClass[] {
  const out: DemoClass[] = [];
  for (let c = findClass(path); c?.parent; c = findClass(c.parent)) {
    const p = findClass(c.parent);
    if (p) out.push(p);
  }
  return out;
}
`
  );
}

function animsModule(sequences, rows) {
  return (
    header('dump/raw/Game/CatapultHero/精灵片 and the live tables', 'Flipbook animation sequences: length, notifies; the sequences of every row with 动画.精灵动画序列.') +
    `import type { AssetPath } from './types.ts';

export interface DemoAnimNotify {
  /** Notify blueprint, e.g. 'CatapultHero/BP/通知/动画攻击检测'. */
  readonly class: string;
  readonly name: string;
  /** Seconds from the start of the sequence (cooked data omits 0). */
  readonly time: number;
  /** Notify states: their Duration; 0 for plain notifies. */
  readonly duration: number;
  readonly track: number;
  readonly [property: string]: unknown;
}
/** Structurally an AnimDef of src/core/sim/types.ts. */
export interface DemoAnimSequence {
  readonly path: AssetPath;
  /** ΣFrameRun / FramesPerSecond of the first flipbook (UPaperFlipbook::GetTotalDuration). */
  readonly length: number;
  readonly frames: number;
  readonly fps: number;
  readonly flipbooks: readonly AssetPath[];
  readonly notifies: readonly DemoAnimNotify[];
}

export const demoAnims: Readonly<Record<AssetPath, DemoAnimSequence>> = {
${entries(sequences)}};

/** 'table:row' -> its 动画.精灵动画序列 (index i is the Demo's sequence i; null where the row leaves a slot empty). */
export const actorAnims: Readonly<Record<string, readonly (AssetPath | null)[]>> = {
${entries(rows)}};

/** Length in seconds of a sequence; throws for an unknown path. */
export function animLength(path: AssetPath): number {
  if (!Object.hasOwn(demoAnims, path)) throw new Error(\`unknown animation sequence \${path}\`);
  return demoAnims[path].length;
}
`
  );
}

function tagsModule({ tags, redirects }) {
  return (
    header('dump/config/CatapultHero/Config/DefaultGameplayTags.ini', 'The registered gameplay tags (ini order) and the tag redirects.') +
    `
/** Every registered tag, in the ini's order. Parents are implicit (a.b.c registers a and a.b). */
export const demoTags: readonly string[] = [
${list(tags.map(t => t.tag))}];

/** Non-empty DevComments by tag. */
export const tagComments: Readonly<Record<string, string>> = {
${entries(Object.fromEntries(tags.filter(t => t.comment).map(t => [t.tag, t.comment])))}};

/** Old tag name -> new tag name (UE applies these when a tag is loaded). */
export const tagRedirects: Readonly<Record<string, string>> = {
${entries(redirects)}};

/** The tag a name resolves to after the redirects. */
export function redirectTag(tag: string): string {
  const seen = new Set<string>();
  while (Object.hasOwn(tagRedirects, tag) && !seen.has(tag)) {
    seen.add(tag);
    tag = tagRedirects[tag];
  }
  return tag;
}

/** a.b.c -> ['a', 'a.b', 'a.b.c']. */
export function tagWithParents(tag: string): string[] {
  const parts = tag.split('.');
  return parts.map((_, i) => parts.slice(0, i + 1).join('.'));
}
`
  );
}

