// Renders src/content/demo: one typed data module per table (the payload between "= " and ";" is plain JSON, one
// row per line), the curve, enum and struct modules, types.ts, tables.ts (the typed accessors index.ts re-exports),
// registry.ts and manifest.json.
import { assetName, parseType } from './normalize.mjs';
import { FRAMEWORK_TYPES } from './framework-types.mjs';

const json = v => JSON.stringify(v);
const header = source => `// Generated by tools/data/import-demo.mjs from ${source}. Do not edit: re-run the importer (src/content/README.md).\n`;
const IDENTIFIER = /^[\p{ID_Start}$_][\p{ID_Continue}$]*$/u;
const ident = name => {
  if (!IDENTIFIER.test(name)) throw new Error(`"${name}" is not a valid identifier`);
  return name;
};
const prop = name => (IDENTIFIER.test(name) ? name : json(name));

/** `{ "k": v, ... }` with one entry per line at `depth` (two spaces per level); values on a single line. */
function block(entries, depth) {
  if (!entries.length) return '{}';
  const pad = '  '.repeat(depth);
  return `{\n${entries.map(([k, v]) => `${pad}  ${json(k)}: ${v}`).join(',\n')}\n${pad}}`;
}
const rowsBlock = (rows, depth) => block(Object.entries(rows).map(([k, v]) => [k, json(v)]), depth);

function tableModule(t) {
  const { table } = t;
  const rowType = table.row_struct;
  const keyType = `DemoRowNames[${json(t.name)}]`;
  if (table.class === 'CompositeDataTable') {
    const parents = table.parent_tables.map(assetName);
    const meta = block(
      [
        ['asset', json(table.asset)],
        ['class', json(table.class)],
        ['row_struct', json(rowType)],
        ['deprecated', json(t.deprecated)],
        ['parent_tables', json(table.parent_tables)],
      ],
      1,
    );
    return (
      header(`dump/${t.source}`) +
      `import type { DemoCompositeTable, DemoRowNames, ${rowType} } from '../types.ts';\n` +
      `import { mergeParents } from '../composite.ts';\n` +
      parents.map(p => `import ${ident(p)} from './${p}.ts';\n`).join('') +
      `\nconst table: DemoCompositeTable<${rowType}, ${keyType}> = /* @__PURE__ */ mergeParents<${rowType}, ${keyType}>(\n  ${meta},\n  [${parents.join(', ')}],\n);\nexport default table;\n`
    );
  }
  const body = block(
    [
      ['asset', json(table.asset)],
      ['class', json(table.class)],
      ['row_struct', json(rowType)],
      ['deprecated', json(t.deprecated)],
      ['flags', block(Object.entries(t.flags).map(([k, v]) => [k, json(v)]), 1)],
      ['rows', rowsBlock(table.rows, 1)],
    ],
    0,
  );
  return (
    header(`dump/${t.source}`) +
    `import type { DemoRowNames, DemoTable, ${rowType} } from '../types.ts';\n\n` +
    `const table: DemoTable<${rowType}, ${keyType}> = ${body};\nexport default table;\n`
  );
}

function curveTableModule(c) {
  const [curve] = c.curves;
  const name = assetName(c.asset);
  const body = block(
    [
      ['asset', json(c.asset)],
      ['name', json(curve.name)],
      ['class', json(curve.class)],
      ['mode', json(curve.mode)],
      ['rows', rowsBlock(curve.rows, 1)],
    ],
    0,
  );
  return header(`dump/${c.source}`) + `import type { DemoCurveTable, DemoRowNames } from '../types.ts';\n\nconst table: DemoCurveTable<DemoRowNames[${json(name)}]> = ${body};\nexport default table;\n`;
}

function curveAssetsModule(assets) {
  const body = block(assets.map(a => [a.asset, json({ deprecated: a.deprecated, curves: a.curves })]), 0);
  return (
    header('dump/curves/CatapultHero (every curve asset except the curve tables)') +
    `import type { DemoCurveAsset } from '../types.ts';\n\n` +
    `/** Timeline curves owned by blueprints (CurveFloat) and the 轨迹渐变 colour ramp (CurveLinearColor), by asset path. */\n` +
    `const assets: Readonly<Record<string, DemoCurveAsset>> = ${body};\nexport default assets;\n`
  );
}

function enumsModule(enums) {
  const body = block(Object.entries(enums).map(([k, v]) => [k, json(v)]), 0);
  return header('dump/enums/CatapultHero') + `import type { DemoEnums } from '../types.ts';\n\nconst enums: DemoEnums = ${body};\nexport default enums;\n`;
}

function structsModule(structs) {
  const body = block(Object.entries(structs).map(([k, v]) => [k, json(v)]), 0);
  return header('dump/structs/CatapultHero') + `import type { DemoStructs } from '../types.ts';\n\nconst structs: DemoStructs = ${body};\nexport default structs;\n`;
}

const ENGINE_TYPES = {
  DataTableRowHandle: 'DataTableRowHandle',
  GameplayTagContainer: 'GameplayTagContainer',
  GameplayTag: 'GameplayTag',
  InputRange: 'InputRange',
  Vector: 'Vector',
  Vector2D: 'Vector2D',
  Transform: 'Transform',
};

function tsType(type, structNames) {
  switch (type.kind) {
    case 'prim':
      return { Bool: 'boolean', Int: 'number', Double: 'number', Str: 'string', Name: 'string', Text: 'FText' }[type.name];
    case 'enum':
      return type.name;
    case 'ref':
      return 'AssetPath | null';
    case 'array': {
      const item = tsType(type.item, structNames);
      return `readonly ${item.includes('|') ? `(${item})` : item}[]`;
    }
    case 'map':
      return `Readonly<Record<string, ${tsType(type.value, structNames)}>>`;
    case 'struct':
      if (structNames.has(type.name)) return type.name;
      if (ENGINE_TYPES[type.name]) return ENGINE_TYPES[type.name];
  }
  throw new Error(`no TypeScript type for ${JSON.stringify(type)}`);
}

function typesModule({ tables, curveTables, enumDefs, structDefs }) {
  const structNames = new Set(Object.keys(structDefs));
  const out = [header('dump/structs, dump/enums, dump/datatables and dump/curves'), FRAMEWORK_TYPES];
  out.push('\n// ---- Enums (dump/enums): each value is its display name; demoEnums maps it to the UE value. ----\n');
  for (const [name, def] of Object.entries(enumDefs)) {
    const values = def.values.filter(v => v.display !== null).map(v => json(v.display));
    out.push(`/** ${def.asset.replace('/Game/', '')} */\nexport type ${ident(name)} = ${values.join(' | ')};\n`);
  }
  out.push(`\nexport interface DemoEnumTypes {\n${Object.keys(enumDefs).map(n => `  ${n}: ${n};\n`).join('')}}\n`);
  out.push('\n// ---- User structs (dump/structs). ----\n');
  for (const [name, def] of Object.entries(structDefs)) {
    const doc = `/** ${def.asset.replace('/Game/', '')} */\n`;
    if (name === '结构_科学数') {
      out.push(
        `${doc}export interface 结构_科学数 {\n` +
          `  /**\n   * 系数 × 10^指数 computed like 函数库_科学数.科学数变普通 (0 when 系数 is 0), with the same double rounding\n` +
          `   * (1.1e2 is 110.00000000000001). 科学数 arithmetic should use 系数 and 指数.\n   */\n  readonly 值: number;\n` +
          `  readonly 系数: number;\n  readonly 指数: number;\n}\n`,
      );
      continue;
    }
    const fields = def.fields.map(f => `  readonly ${prop(f.name)}: ${tsType(parseType(f.type), structNames)};\n`).join('');
    out.push(`${doc}export interface ${ident(name)} {\n${fields}}\n`);
  }
  out.push(`\nexport interface DemoStructTypes {\n${Object.keys(structDefs).map(n => `  ${n}: ${n};\n`).join('')}}\n`);
  out.push('\n// ---- Row names of every table and curve table, in the Demo\'s order (dropped test rows excluded). ----\n');
  const names = [];
  for (const t of tables) {
    const union =
      t.table.class === 'CompositeDataTable'
        ? t.table.parent_tables.map(p => `DemoRowNames[${json(assetName(p))}]`).join(' | ')
        : Object.keys(t.table.rows).map(json).join(' | ') || 'never';
    names.push(`  ${json(t.name)}: ${union};\n`);
  }
  for (const c of curveTables) names.push(`  ${json(assetName(c.asset))}: ${Object.keys(c.curves[0].rows).map(json).join(' | ')};\n`);
  out.push(`export interface DemoRowNames {\n${names.join('')}}\n`);
  return out.join('');
}

function tablesModule({ tables, curveTables }) {
  const live = tables.filter(t => !t.deprecated);
  return (
    header('the generated data modules') +
    `// One named export per live table (过期 tables stay in data/ but are not exported), plus curves, enums, structs.\n` +
    live.map(t => `export { default as ${ident(t.name)} } from './data/${t.name}.ts';\n`).join('') +
    curveTables.map(c => `export { default as ${ident(assetName(c.asset))} } from './data/${assetName(c.asset)}.ts';\n`).join('') +
    `export { default as demoCurveAssets } from './data/curve-assets.ts';\n` +
    `export { default as demoEnums } from './data/enums.ts';\n` +
    `export { default as demoStructs } from './data/structs.ts';\n`
  );
}

function registryModule({ tables }) {
  const live = tables.filter(t => !t.deprecated);
  return (
    header('the generated data modules') +
    `import type { AssetPath, DemoTable } from './types.ts';\n` +
    live.map(t => `import ${ident(t.name)} from './data/${t.name}.ts';\n`).join('') +
    `\n/**\n * Every live table by asset path, for references that can point at any table (DataTableRowHandle.DataTable,\n` +
    ` * Object<DataTable> fields). It imports all of them: modules that know their tables should import those instead.\n */\n` +
    `export const demoTablesByAsset: Readonly<Record<AssetPath, DemoTable<unknown>>> = {\n` +
    live.map(t => `  ${json(t.table.asset)}: ${t.name},\n`).join('') +
    `};\n`
  );
}

const bytes = text => Buffer.byteLength(text, 'utf8');

export function emitFiles({ tables, curveAssets, enums, structs, enumDefs, structDefs, dumpDir }) {
  const files = new Map();
  for (const t of tables) files.set(`data/${t.name}.ts`, tableModule(t));
  const curveTables = curveAssets.filter(c => c.curves.length === 1 && c.curves[0].class === 'CurveTable');
  for (const c of curveTables) files.set(`data/${assetName(c.asset)}.ts`, curveTableModule(c));
  const otherCurves = curveAssets.filter(c => !curveTables.includes(c));
  files.set('data/curve-assets.ts', curveAssetsModule(otherCurves));
  files.set('data/enums.ts', enumsModule(enums));
  files.set('data/structs.ts', structsModule(structs));
  files.set('types.ts', typesModule({ tables, curveTables, enumDefs, structDefs }));
  files.set('tables.ts', tablesModule({ tables, curveTables }));
  files.set('registry.ts', registryModule({ tables }));

  const totalBytes = [...files.values()].reduce((n, text) => n + bytes(text), 0);
  const dataBytes = [...files].filter(([p]) => p.startsWith('data/')).reduce((n, [, text]) => n + bytes(text), 0);
  const count = (list, f) => list.reduce((n, x) => n + f(x), 0);
  const plain = tables.filter(t => t.table.class !== 'CompositeDataTable');
  const composite = tables.filter(t => t.table.class === 'CompositeDataTable');
  const manifest = {
    generator: 'tools/data/import-demo.mjs',
    dump: dumpDir,
    totals: {
      tables: tables.length,
      composite_tables: composite.length,
      deprecated_tables: count(tables, t => (t.deprecated ? 1 : 0)),
      /** Rows of all tables in the dump, composites included. */
      dump_rows: count(tables, t => t.dumpRows),
      /** Rows kept in the DataTables (composites excluded: they are views of these). */
      rows: count(plain, t => Object.keys(t.table.rows).length),
      /** Rows the composite tables resolve to. */
      composite_rows: count(composite, t => Object.keys(t.table.rows).length),
      dropped_rows: count(plain, t => Object.keys(t.dropped).length),
      flagged_rows: count(plain, t => Object.keys(t.flags).length),
      curve_assets: curveAssets.length,
      curves: count(curveAssets, c => count(c.curves, x => (x.rows ? Object.keys(x.rows).length : 1))),
      enums: Object.keys(enums).length,
      structs: Object.keys(structs).length,
      data_bytes: dataBytes,
      bytes: totalBytes,
    },
    excluded: [
      'Rows whose key marks them as tests (测试) and that no kept row references: listed under tables.*.dropped.',
      '过期 (deprecated) tables and curve assets: kept in data/ with deprecated: true, not exported from index.ts or registry.ts.',
      'FText ns/key (localization ids): only {zh, en} is kept.',
      'Enum NewEnumeratorN names and numeric values in rows: replaced by the display name (demoEnums has the mapping).',
      'The class prefix of object references (e.g. SoundWave\'...\'): the field types in demoStructs name the class.',
      'Struct GUIDs and property flags; curve export indices.',
      'Composite tables store no rows of their own: they are merged from their parents at load (src/content/demo/composite.ts).',
      'Dump folders not imported: blueprints, blueprints-pseudo, widgets, levels, native, config, raw.',
    ],
    tables: Object.fromEntries(
      tables.map(t => [
        t.name,
        {
          source: t.source,
          module: `data/${t.name}.ts`,
          class: t.table.class,
          row_struct: t.table.row_struct,
          deprecated: t.deprecated,
          dump_rows: t.dumpRows,
          rows: Object.keys(t.table.rows).length,
          texts_without_en: [...t.textsWithoutEn.values()].reduce((n, x) => n + x, 0),
          bytes: bytes(files.get(`data/${t.name}.ts`)),
          dropped: t.dropped,
          flags: t.flags,
        },
      ]),
    ),
    curve_assets: Object.fromEntries(
      curveAssets.map(c => [
        c.asset,
        {
          source: c.source,
          module: curveTables.includes(c) ? `data/${assetName(c.asset)}.ts` : 'data/curve-assets.ts',
          deprecated: c.deprecated,
          curves: c.curves.map(x => x.name),
        },
      ]),
    ),
  };
  files.set('manifest.json', `${JSON.stringify(manifest, null, 1)}\n`);
  return { files, manifest };
}
