// node tools/bp/skeleton.mjs <asset path> --batch <card-id> [--root <checkout>] [--dump <dir>] [--force] [--dry]
//
// Writes the translation skeleton of one Demo blueprint (studio/ARCHITECTURE.md §7.2–§7.4):
// - src/content/bp/<path minus CatapultHero/BP/>.ts: citation header, the class extending its manifest parent's TS
//   class, field initializers from the CDO (own variables only; inherited CDO overrides are listed, the runtime applies
//   them from the manifest), and one method per function and event the blueprint defines, with its pseudo-code pasted
//   as comments. An override copies the parent's TS signature and calls super until it is translated; a function the
//   blueprint introduces reports itself unported.
// - the registration line in src/content/bp/batches/<card-id>.ts;
// - tests/<card-id>/<name>.test.ts: a test skeleton citing the labels.
// Existing files are kept unless --force; --dry prints the module instead of writing anything.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { mangle } from '../data/mangle.mjs';
import { parseVarType } from '../data/classes.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const BP_PREFIX = 'CatapultHero/BP/';

/** Demo base classes whose TS declarations live in src/core (generated by core-contracts), by asset path. */
export const CORE_BASES = {
  'CatapultHero/BP/Skill/蓝图_效果': 'src/core/ability/effect.ts',
  'CatapultHero/BP/Skill/蓝图_能力': 'src/core/ability/ability.ts',
  'CatapultHero/BP/Skill/蓝图_发射物': 'src/core/ability/projectile.ts',
  'CatapultHero/BP/Actor/BP_ManeActor': 'src/core/sim/actor.ts',
  'CatapultHero/BP/Actor/BP_Actor_Player': 'src/core/sim/player.ts',
  'CatapultHero/BP/Actor/BP_Actor_Other': 'src/core/sim/other.ts',
  'CatapultHero/BP/Actor/BP_Actor_Card': 'src/core/sim/card.ts',
  'CatapultHero/BP/Actor/蓝图_动作游戏模式': 'src/core/sim/mode.ts',
  'CatapultHero/BP/环境/修炼/修炼系统': 'src/core/sim/cult.ts',
};
/** The abstract root every Demo object extends (BpObject, src/core/sim/object.ts) for native parents. */
const ROOT_BASE = { file: 'src/core/sim/object.ts', name: 'BpObject' };

/** Where the module of `asset` lives; `base` is src/content/bp except for the compile fixtures of tests/content-bpkit. */
export const modulePath = (asset, base = 'src/content/bp') => `${base}/${asset.slice(BP_PREFIX.length)}.ts`;
const posix = p => p.split(path.sep).join('/');
const relImport = (fromFile, toFile) => {
  const r = posix(path.relative(path.dirname(fromFile), toFile));
  return r.startsWith('.') ? r : `./${r}`;
};

/** Pseudo file -> { functions: [{name, params, overrides, body}], entries: {event: lines}, cdoOverrides }. */
export function parsePseudo(text) {
  const lines = text.split(/\r?\n/);
  const functions = [];
  for (let i = 0; i < lines.length; i++) {
    const m = /^ {4}function (\S+?)\((.*)\)(?:: (\S+))?(\s+\/\/ overrides (.*?))? \{$/.exec(lines[i]) ?? /^ {4}function (\S+?)\((.*)\)(?:: (\S+))?(\s+\/\/ overrides (.*?))?\s*\{$/.exec(lines[i]);
    if (!m) continue;
    const start = i;
    let j = i + 1;
    while (j < lines.length && lines[j] !== '    }') j++;
    const flags = /^ {4}\/\/ flags: (.*)$/.exec(lines[start - 1] ?? '')?.[1] ?? '';
    functions.push({ name: m[1], params: splitParams(m[2]), returns: m[3] ?? null, overrides: m[5] ?? null, flags, body: lines.slice(start + 1, j) });
    i = j;
  }
  const entries = {};
  const ug = functions.find(f => f.name.startsWith('ExecuteUbergraph_'));
  if (ug) {
    let current = null;
    for (const l of ug.body) {
      const e = /^ {2}\/\/ ===== entry from event: (.+?) =====$/.exec(l);
      if (e) current = entries[e[1]] = [];
      else if (current) current.push(l);
    }
  }
  return { functions, entries };
}

function splitParams(text) {
  const out = [];
  let depth = 0, cur = '';
  for (const c of text) {
    if (c === '<') depth++;
    if (c === '>') depth--;
    if (c === ',' && depth === 0) {
      out.push(cur.trim());
      cur = '';
    } else cur += c;
  }
  if (cur.trim()) out.push(cur.trim());
  return out.map(p => {
    const m = /^(out |ref )?(.+?): (.+)$/.exec(p);
    return m ? { name: m[2], type: m[3], out: m[1]?.trim() === 'out', ref: m[1]?.trim() === 'ref' } : { name: p, type: 'unknown', out: false, ref: false };
  });
}

/** TS type of a blueprint variable type (refined by translators where needed). */
export function tsType(text) {
  const t = parseVarType(text);
  switch (t.kind) {
    case 'prim':
      return { Bool: 'boolean', Int: 'number', Int64: 'number', Double: 'number', Float: 'number', Byte: 'number', Str: 'string', Name: 'string' }[t.name] ?? 'unknown';
    case 'enum':
      return 'string';
    case 'array':
      return `${wrap(tsType(text.slice(text.indexOf('<') + 1, -1)))}[]`;
    case 'map':
      return `Record<string, ${tsType(splitTopLevel(text.slice(4, -1))[1])}>`;
    case 'struct':
      if (t.name === 'GameplayTag') return 'string';
      if (t.name === 'GameplayTagContainer') return 'string[]';
      if (t.name === '结构_科学数') return '{ 系数: number; 指数: number }';
      return 'unknown';
    default:
      return 'unknown';
  }
}
const wrap = t => (/^[\w$\p{L}]+$/u.test(t) ? t : `(${t})`);
function splitTopLevel(text) {
  let depth = 0;
  for (let i = 0; i < text.length; i++) {
    if (text[i] === '<') depth++;
    else if (text[i] === '>') depth--;
    else if (text[i] === ',' && depth === 0) return [text.slice(0, i).trim(), text.slice(i + 1).trim()];
  }
  return [text, 'unknown'];
}

/** The TS source file and class name that a manifest parent resolves to. */
function parentModule(def, base) {
  if (!def.parent) return ROOT_BASE;
  if (CORE_BASES[def.parent]) return { file: CORE_BASES[def.parent], name: mangle(def.parent.slice(def.parent.lastIndexOf('/') + 1)) };
  return { file: modulePath(def.parent, base), name: mangle(def.parent.slice(def.parent.lastIndexOf('/') + 1)) };
}

/** Names a TS source file imports or declares: name -> the file (relative to the checkout) that provides it. */
function providers(root, rel) {
  const src = fs.readFileSync(path.join(root, rel), 'utf8');
  const out = new Map();
  for (const m of src.matchAll(/^import\s+(?:type\s+)?\{([^}]*)\}\s+from\s+'([^']+)'/gmu)) {
    const from = posix(path.normalize(path.join(path.dirname(rel), m[2])));
    for (const n of m[1].split(',').map(x => x.trim().replace(/^type\s+/, '').split(/\s+as\s+/).pop()).filter(Boolean)) out.set(n, from);
  }
  for (const m of src.matchAll(/^export\s+(?:abstract\s+)?(?:class|interface|type|const|function)\s+([\p{L}\p{N}_$]+)/gmu)) out.set(m[1], rel);
  return out;
}

/** A method signature of `name` in the parent chain's TS sources: { params, returns, types: name -> file } or null. */
function findSignature(root, classes, def, name, base) {
  for (let p = parentModule(def, base), d = def; ; ) {
    const file = path.join(root, p.file);
    if (fs.existsSync(file)) {
      const src = fs.readFileSync(file, 'utf8');
      const re = new RegExp(`^\\s+(?:override\\s+)?${name.replace(/[$]/g, '\\$')}\\s*\\(([^)]*)\\)\\s*(?::\\s*([^{]+?))?\\s*\\{`, 'mu');
      const m = re.exec(src);
      if (m) {
        const params = m[1].trim();
        const returns = (m[2] ?? 'void').trim();
        const prov = providers(root, p.file);
        const types = new Map();
        for (const t of `${params.replace(/[\p{L}\p{N}_$]+\??\s*:/gu, ':')} ${returns}`.match(/[\p{L}_$][\p{L}\p{N}_$]*/gu) ?? []) {
          if (prov.has(t)) types.set(t, prov.get(t));
        }
        return { params, returns, types };
      }
    }
    if (!d.parent || p === ROOT_BASE) return null;
    d = classes[d.parent];
    if (!d) return null;
    p = parentModule(d, base);
  }
}

/** A TS literal: strings in single quotes (the repo's style), everything else as JSON. */
const IDENT = /^[\p{ID_Start}$_][\p{ID_Continue}$]*$/u;
const literal = v => {
  if (typeof v === 'string') return `'${JSON.stringify(v).slice(1, -1).replace(/\\"/g, '"').replace(/'/g, "\\'")}'`;
  if (Array.isArray(v)) return `[${v.map(literal).join(', ')}]`;
  if (v && typeof v === 'object') {
    const e = Object.entries(v);
    return e.length ? `{ ${e.map(([k, x]) => `${IDENT.test(k) ? k : literal(k)}: ${literal(x)}`).join(', ')} }` : '{}';
  }
  return JSON.stringify(v);
};
const fieldType = (v, decl) => {
  const t = decl ? tsType(decl.type) : 'unknown';
  if (t !== 'unknown') return t;
  return v === null ? 'unknown' : Array.isArray(v) ? 'unknown[]' : typeof v === 'object' ? 'Record<string, unknown>' : typeof v;
};

/** Source of the module for `asset`. */
export function moduleSource({ asset, batch, classes, pseudoText, blueprint, root, base = 'src/content/bp' }) {
  const def = classes[asset];
  if (!def) throw new Error(`${asset} is not in src/content/demo/classes.ts`);
  const name = mangle(def.name);
  const file = modulePath(asset, base);
  const parent = parentModule(def, base);
  const { functions, entries } = parsePseudo(pseudoText);
  const decls = new Map((blueprint?.variables ?? []).map(v => [mangle(v.name), v]));

  const out = [];
  out.push('/**');
  out.push(` * ${def.name}: TODO one-line summary of what the blueprint does.`);
  out.push(` * Demo: ${asset} (dump/blueprints-pseudo/${asset}.txt)`);
  out.push(` * Parent: ${def.parent ? def.parent.slice(def.parent.lastIndexOf('/') + 1) : `native ${def.native}`}. CDO tags (manifest): ${def.tags.length ? def.tags.join(', ') : 'none'}.`);
  out.push(` * Rows: ${def.rows.length ? def.rows.join(', ') : 'none'}.`);
  out.push(` * Batch: ${batch}.`);
  out.push(' */');
  out.push(`import { ${parent.name} } from '${relImport(file, parent.file)}';`);
  const importAt = out.length;
  const typeImports = new Map([['AssetPath', 'src/content/demo/types.ts']]);
  out.push('');
  out.push(`export class ${name} extends ${parent.name} {`);
  out.push(`  static override readonly path: AssetPath = ${literal(asset)};`);
  for (const [k, v] of Object.entries(def.vars)) out.push(`  ${k}: ${fieldType(v, decls.get(k))} = ${literal(v)};`);
  const ov = Object.entries(def.overrides ?? {});
  if (ov.length) {
    out.push('  // CDO overrides of inherited variables (applied by the runtime from the manifest, never redeclared):');
    for (const [k, v] of ov) out.push(`  //   ${k} = ${literal(v)}`);
  }
  for (const f of functions) {
    if (f.name.startsWith('ExecuteUbergraph_')) continue;
    const isEvent = f.body.some(l => /goto UBERGRAPH@L\d+/.test(l));
    const pseudo = isEvent ? (entries[f.name] ?? f.body) : f.body;
    const method = mangle(f.name);
    out.push('');
    const sig = f.overrides ? findSignature(root, classes, def, method, base) : null;
    if (sig) {
      for (const [t, from] of sig.types) if (t !== parent.name) typeImports.set(t, from);
      const args = sig.params ? sig.params.split(',').map(p => p.trim().replace(/^\.\.\./, '...').split(/[?:=]/)[0].trim()).filter(Boolean) : [];
      out.push(`  override ${method}(${sig.params}): ${sig.returns} {`);
      for (const l of pseudo) out.push(`    // ${l.trim()}`.trimEnd());
      const call = `super.${method}(${args.join(', ')})`;
      out.push(sig.returns === 'void' ? `    ${call};` : `    return ${call};`);
    } else {
      const ins = f.params.filter(p => !p.out);
      const outs = f.params.filter(p => p.out);
      const params = ins.map(p => `_${mangle(p.name)}: ${tsType(p.type)}`).join(', ');
      const returns = outs.length || f.returns ? 'unknown' : 'void';
      if (f.overrides) out.push(`  // SPEC-GAP: overrides ${f.overrides}, but no TS signature was found in the parent chain.`);
      out.push(`  ${method}(${params}): ${returns} {`);
      for (const l of pseudo) out.push(`    // ${l.trim()}`.trimEnd());
      out.push(`    this.world.unported(${literal(`${def.name}.${f.name}`)});`);
      if (returns !== 'void') out.push('    return undefined;');
    }
    out.push('  }');
  }
  out.push('}');
  const byFile = new Map();
  for (const [t, from] of [...typeImports].sort(([a], [b]) => (a < b ? -1 : 1))) byFile.set(from, [...(byFile.get(from) ?? []), t]);
  out.splice(importAt, 0, ...[...byFile].map(([from, names]) => `import type { ${names.join(', ')} } from '${relImport(file, from)}';`));
  return `${out.join('\n')}\n`;
}

/**
 * Adds `name` (imported from `file`) to a batch file of src/content/bp/batches (the format core-contracts pre-creates:
 * `const batch: readonly BpCtor[] = [ … ];`), creating the file if needed. Returns the new source.
 */
export function batchSource(existing, batchFile, file, name) {
  const imp = `import { ${name} } from '${relImport(batchFile, file)}';`;
  const fresh = [`import type { BpCtor } from '${relImport(batchFile, 'src/core/sim/types.ts')}';`, '', 'const batch: readonly BpCtor[] = [];', 'export default batch;', ''];
  let src = existing ?? fresh.join('\n');
  if (src.includes(imp)) return src;
  const m = /(const batch: readonly BpCtor\[\] = \[)([\s\S]*?)(\];)/.exec(src);
  if (!m) throw new Error(`${batchFile}: no "const batch: readonly BpCtor[] = [...];" to register into`);
  const items = m[2].split(',').map(x => x.trim()).filter(Boolean);
  items.push(name);
  src = src.replace(m[0], `${m[1]}\n${items.map(i => `  ${i},\n`).join('')}${m[3]}`);
  const lines = src.split('\n');
  let at = 0;
  for (let i = 0; i < lines.length; i++) if (lines[i].startsWith('import ')) at = i + 1;
  lines.splice(at, 0, imp);
  return lines.join('\n');
}

export function testSource({ asset, batch, name, def, testFile, file }) {
  return `import { describe, expect, it } from 'vitest';
import { ${name} } from '${relImport(testFile, file)}';

// ${def.name} (${asset}), batch ${batch}: one vector per branch, citing the pseudo labels (studio/ARCHITECTURE.md §7.5).
describe('${def.name}', () => {
  it('is registered under its Demo asset path', () => {
    expect(${name}.path).toBe(${literal(asset)});
  });
  it.todo('vectors: state before -> trigger -> state after (cite the labels)');
});
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { values, positionals } = parseArgs({
    allowPositionals: true,
    options: {
      batch: { type: 'string' },
      root: { type: 'string', default: path.resolve(HERE, '..', '..') },
      dump: { type: 'string', default: 'D:/TAPTAPGAME_codex/reference/dump' },
      force: { type: 'boolean', default: false },
      dry: { type: 'boolean', default: false },
    },
    strict: true,
  });
  if (positionals.length !== 1 || !values.batch) {
    console.error('usage: node tools/bp/skeleton.mjs <asset path> --batch <card-id> [--root dir] [--force] [--dry]');
    process.exit(2);
  }
  let asset = positionals[0].replace(/^\/?Game\//, '').replace(/\.txt$|\.ts$/, '');
  if (!asset.startsWith(BP_PREFIX)) asset = BP_PREFIX + asset;
  const { demoClasses } = await import(new URL(`file:///${posix(path.join(values.root, 'src/content/demo/classes.ts'))}`).href);
  const pseudoText = fs.readFileSync(path.join(values.dump, 'blueprints-pseudo', `${asset}.txt`), 'utf8');
  const blueprint = JSON.parse(fs.readFileSync(path.join(values.dump, 'blueprints', `${asset}.json`), 'utf8'));
  const src = moduleSource({ asset, batch: values.batch, classes: demoClasses, pseudoText, blueprint, root: values.root });
  if (values.dry) {
    process.stdout.write(src);
    process.exit(0);
  }
  const def = demoClasses[asset];
  const name = mangle(def.name);
  const file = modulePath(asset);
  const batchFile = `src/content/bp/batches/${values.batch}.ts`;
  const testFile = `tests/${values.batch}/${def.name}.test.ts`;
  const write = (rel, text, force) => {
    const full = path.join(values.root, rel);
    if (fs.existsSync(full) && !force) return console.error(`kept ${rel}`);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, text);
    console.error(`wrote ${rel}`);
  };
  write(file, src, values.force);
  const batchFull = path.join(values.root, batchFile);
  write(batchFile, batchSource(fs.existsSync(batchFull) ? fs.readFileSync(batchFull, 'utf8') : null, batchFile, file, name), true);
  write(testFile, testSource({ asset, batch: values.batch, name, def, testFile, file }), values.force);
}
